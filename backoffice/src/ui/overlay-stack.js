/**
 * Стек открытых слоёв: панель, диалог, лист.
 *
 * Escape обязан закрывать ВЕРХНИЙ слой, а не все сразу. Без стека это
 * ломалось так: панель визита и диалог отмены оба слушают клавиатуру на
 * документе в фазе перехвата, обработчики вызываются в порядке
 * регистрации, и панель — открытая первой — успевала закрыться раньше,
 * чем диалог. Хостес нажимал Escape, чтобы отказаться от отмены брони, и
 * терял всю карточку визита вместе с несохранёнными правками.
 *
 * `stopPropagation` здесь не помогает: он останавливает распространение
 * между УЗЛАМИ, а не между слушателями одного и того же узла.
 */

const stack = []

/**
 * Зарегистрировать слой. Возвращает функцию снятия — её место в
 * `useEffect`, чтобы слой уходил вместе с компонентом.
 */
export function pushLayer(layer) {
  stack.push(layer)
  return () => {
    const index = stack.lastIndexOf(layer)
    if (index >= 0) stack.splice(index, 1)
  }
}

/** Верхний ли это слой — то есть ему ли принадлежат Escape и Tab */
export function isTopLayer(layer) {
  return stack.length > 0 && stack[stack.length - 1] === layer
}

/** Сколько слоёв открыто (для тестов и отладки) */
export const layerCount = () => stack.length
