/**
 * Куда встаёт фокус, когда слой открылся.
 *
 * Раньше формы кабинета фокусировали первое поле всегда — и на телефоне
 * это означало, что вместе с формой выезжает клавиатура: она занимает
 * половину экрана, лист приходится проматывать, а человек ещё даже не
 * решил, что он тут делает. Открыть бронь, чтобы посмотреть свободное
 * время, стало нельзя без того, чтобы сначала убрать клавиатуру.
 *
 * Поэтому автофокус в ПОЛЕ остаётся там, где он ничего не заслоняет —
 * там, где есть мышь. На сенсорном экране фокус входит в сам слой:
 * читалка объявляет заголовок, ловушка Tab работает, но клавиатура
 * появляется только когда человек сам тапнул по полю.
 *
 * Это не про размер экрана, а про указатель: телефон в ландшафте шире
 * 640px, а клавиатуру выбрасывает так же.
 */

/** Палец, а не мышь */
export function coarsePointer() {
  return typeof window !== 'undefined'
    && typeof window.matchMedia === 'function'
    && window.matchMedia('(pointer: coarse)').matches
}

/**
 * Ввести фокус в открывшийся слой: в поле — если есть мышь, иначе в сам
 * слой. `panel` обязан быть фокусируемым (`tabIndex={-1}`), иначе фокус
 * останется на кнопке-источнике за пределами слоя.
 */
export function focusOnOpen(panel, field) {
  if (!coarsePointer() && field) {
    field.focus()
    return
  }
  panel?.focus()
}
